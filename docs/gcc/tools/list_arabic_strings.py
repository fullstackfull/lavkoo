#!/usr/bin/env python3
"""Lists every line with Arabic text that a pull request of lavkoo adds to resources/lang, for the native Arabic reader (master tracker M1-13).

usage: list_arabic_strings.py <checkout of lavkoo> [--no-fetch] > ARABIC_TEXT_FOR_REVIEW.md

It reads the remote's pull request refs (`git fetch origin '+refs/pull/*/head:refs/remotes/pull/*'`, skipped with --no-fetch) and, for each pull request in
ascending order, the lines its head adds to resources/lang compared with the merge base with origin/main. A line that an earlier pull request already adds (a stacked
pull request carries the lines of its base) is listed once, under the lowest number. It only reads: nothing is written to the checkout, and nothing leaves the machine.
"""
import collections
import re
import subprocess
import sys

ARABIC = re.compile(r'[؀-ۿ]')
PAIR = re.compile(r'''^\s*(['"])(?P<key>.+?)\1\s*=>\s*(['"])(?P<text>.*)\3\s*,?\s*$''')


def git(repo, *arguments):
    return subprocess.run(['git', '-C', repo, *arguments], capture_output=True, text=True, check=True).stdout


def pull_numbers(repo):
    refs = git(repo, 'for-each-ref', '--format=%(refname)', 'refs/remotes/pull').split()
    return sorted(int(ref.rsplit('/', 1)[1]) for ref in refs)


def added_arabic(repo, number):
    diff = git(repo, 'diff', '--unified=0', 'origin/main...refs/remotes/pull/%d' % number, '--', 'resources/lang')
    path, found = None, []
    for line in diff.splitlines():
        if line.startswith('+++ '):
            path = line[6:] if line.startswith('+++ b/') else line[4:]
        elif line.startswith('+') and ARABIC.search(line):
            match = PAIR.match(line[1:])
            found.append((path, match.group('key') if match else '(not a key and text pair)', (match.group('text') if match else line[1:].strip())))
    return found


def main():
    repo = sys.argv[1]
    if '--no-fetch' not in sys.argv:
        subprocess.run(['git', '-C', repo, 'fetch', 'origin', '+refs/pull/*/head:refs/remotes/pull/*', '--quiet'], check=True)
    seen, by_pull, titles = set(), collections.OrderedDict(), {}
    for number in pull_numbers(repo):
        titles[number] = git(repo, 'log', '-1', '--format=%s', 'refs/remotes/pull/%d' % number).strip()
        fresh = []
        for path, key, text in added_arabic(repo, number):
            if (path, key, text) not in seen:
                seen.add((path, key, text))
                fresh.append((path, key, text))
        if fresh:
            by_pull[number] = fresh

    total = sum(len(rows) for rows in by_pull.values())
    print('# LAVKOO GCC: Arabic text that pull requests add, for a native reader')
    print()
    print('Generated by `docs/gcc/tools/list_arabic_strings.py` from the pull request refs of `lavkoo`; run it again after a pull request moves. It lists every line with Arabic text that a pull')
    print('request adds to `resources/lang` compared with `main`, once, under the lowest pull request number that adds it (a stacked pull request carries the lines of its base).')
    print('**Nothing here has been read by a native reader.** The outcome of that reading is recorded in [REVIEW_GATES.md](REVIEW_GATES.md), never here.')
    print()
    print('%d lines in %d pull requests.' % (total, len(by_pull)))
    print()
    print('| PR | Lines | Title |')
    print('|---|---:|---|')
    for number, rows in by_pull.items():
        print('| %d | %d | %s |' % (number, len(rows), titles[number].replace('|', '\\|')[:110]))
    for number, rows in by_pull.items():
        print()
        print('## PR %d' % number)
        print()
        print('| File | Key | Text |')
        print('|---|---|---|')
        for path, key, text in rows:
            print('| `%s` | `%s` | %s |' % (path, key, text.replace('|', '\\|')))


if __name__ == '__main__':
    main()
